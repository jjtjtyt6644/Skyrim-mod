const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('trainer', {
  run: (commands) => ipcRenderer.invoke('run', commands),
  status: () => ipcRenderer.invoke('status'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (patch) => ipcRenderer.invoke('config:set', patch),
  browseGame: () => ipcRenderer.invoke('config:browse'),
  detectGame: () => ipcRenderer.invoke('config:detect'),
  openLink: (url) => ipcRenderer.invoke('open-link', url),
  window: (action) => ipcRenderer.send('win', action),
  onHotkey: (fn) => ipcRenderer.on('hotkey', (_e, key) => fn(key)),
  version: () => ipcRenderer.invoke('version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: (fn) => ipcRenderer.on('update', (_e, info) => fn(info)),
  onOverlay: (fn) => ipcRenderer.on('overlay', (_e, open) => fn(open)),
  fixDisplay: () => ipcRenderer.invoke('display:fix'),
  fixSubtitles: () => ipcRenderer.invoke('subtitles:fix'),
  setAutoSkip: (on) => ipcRenderer.invoke('autoskip:set', on),
  onAutoSkip: (fn) => ipcRenderer.on('autoskip', (_e, s) => fn(s)),
  getToggles: () => ipcRenderer.invoke('toggles:get'),
  setToggles: (map, changedSave, saveCmds) => ipcRenderer.invoke('toggles:set', map, changedSave, saveCmds),
  sessionCheck: () => ipcRenderer.invoke('session:check'),
  reapplyDone: (full) => ipcRenderer.invoke('reapply:done', full),
  onReapply: (fn) => ipcRenderer.on('reapply', (_e, opts) => fn(opts)),
  mouse: (capture) => ipcRenderer.send('mouse', capture),
  saveNow: () => ipcRenderer.invoke('save:now'),
  lastSave: () => ipcRenderer.invoke('save:last'),
  onAutoSaved: (fn) => ipcRenderer.on('autosaved', (_e, s) => fn(s)),
  onGameClosed: (fn) => ipcRenderer.on('game-closed', (_e, s) => fn(s)),
  mods: {
    plugins: () => ipcRenderer.invoke('mods:plugins'),
    setPlugin: (name, on) => ipcRenderer.invoke('mods:setPlugin', name, on),
    installed: () => ipcRenderer.invoke('mods:installed'),
    install: () => ipcRenderer.invoke('mods:install'),
    uninstall: (name) => ipcRenderer.invoke('mods:uninstall', name),
    nexusList: (kind) => ipcRenderer.invoke('nexus:list', kind),
    nexusValidate: (key) => ipcRenderer.invoke('nexus:validate', key),
    nexusOpen: (id) => ipcRenderer.invoke('nexus:open', id),
    nexusPage: (which) => ipcRenderer.invoke('nexus:openPage', which),
  },
});
